"""Independent local inspection of authored V13 Actions archives.

Usage: python inspect_archive.py downloaded.zip --sha256 <Actions digest>
Requires Pillow. No original assets, Unity or network. The raw receipt and
manifest are inputs from the pinned authored CI job, not generated by this
tool. This checks receipt/byte identity and numeric observations; it never
promotes an inconclusive or drift receipt to a V13 PASS.
"""
import argparse
import hashlib
import io
import json
import math
from pathlib import Path
import re
import zipfile
from PIL import Image

PNG_SHA = (
    "9e6be9b9f97d2bf835fbf3ae21d79f889170b7588dddde3f1c351f85cc3b0a54",
    "5ab65d8dc9fb153f045cdc8ea0b5e8293d0e9006ec22938b7aafcddb9ed575d1",
)
RGBA_SHA = (
    "c4613e57a409b503b1b7c354b38ff2c8656a48a842159ca8c1765b2826c1f895",
    "e284bacc769e1e86fcb71099a4c7473a84c143c540edee397b67c769e466dc1e",
)

def require(condition, reason):
    if not condition:
        raise ValueError(reason)

def digest(data):
    return hashlib.sha256(data).hexdigest()

def inspect(path, expected_sha):
    raw=path.read_bytes()
    require(digest(raw)==expected_sha,"archive_sha256_drift")
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        names=z.namelist()
        require(len(names)==len(set(names)) and len(names)<=64 and all(
            not Path(n).is_absolute() and ".." not in Path(n).parts for n in names
        ),"archive_member_population")
        require(sum(i.file_size for i in z.infolist())<=4*1024*1024,"archive_unbounded")
        require(z.testzip() is None,"archive_CRC_failure")
        data={n:z.read(n) for n in names}
    def j(n):
        return json.loads(data[n])
    m=j("normalmap-unity-manifest.json")
    r=j("normalmap-unity-raw.json")
    v=j("normalmap-unity-verified.json")
    p=j("normalmap-importer-report.json")
    require(r["manifest_sha256"]==digest(data["normalmap-unity-manifest.json"]),"raw_manifest_binding")
    require(m["run_id"]==r["run_id"],"run_id_drift")
    require(p["status"]=="PASS_ACTUAL_AUTHORED_PUBLIC_DXT5NM_SUPPORTED_IMPORTER_STATE_ROUTE_JOIN","V12_replay_missing")
    counts={}
    for n,b in data.items():
        if n.startswith("test_") and n.endswith(".log"):
            s=b.decode("utf-8")
            hit=re.search(r"^Ran (\d+) tests? in ",s,re.M)
            require(hit and re.search(r"^OK$",s,re.M),"regression_log_failure")
            counts[n]=int(hit[1])
    require(counts==p["tests"] and sum(counts.values())==p["total_regression_tests"],"regression_counts")
    result=dict(archive=dict(bytes=len(raw),sha256=digest(raw),crc_verified=True,
        git_blob_sha1=hashlib.sha1(b"blob "+str(len(raw)).encode()+b"\0"+raw).hexdigest(),
        member_sha256={n:digest(b) for n,b in sorted(data.items())}),
        run_id=m["run_id"],source_regressions=sum(counts.values()),V11_V12_controls=p["counterfactual_count"],
        raw_status=r["status"],verified_status=v["status"],actual_Unity_import_verified=v["actual_Unity_import_verified"],
        input_images=[],observations=[],original_assets_read=False,Android_device=False,XAPK=False)
    for i,t in enumerate(m["textures"]):
        b=data[f"normalmap-authored-{i}.png"]
        with Image.open(io.BytesIO(b)) as im:
            rgba=im.tobytes()
            require(im.mode=="RGBA" and im.size==(5,7),"input_png_shape")
            require(digest(b)==t["sha256"]==PNG_SHA[i] and digest(rgba)==RGBA_SHA[i]
                and rgba==bytes.fromhex(t["expected_rgba_hex"]),"input_png_bytes")
            result["input_images"].append(dict(png_sha256=digest(b),rgba_sha256=digest(rgba),
                pixels=35,unique_rgba=len(set(im.getdata()))))
    require(len(result["input_images"])==2,"input_texture_population")
    if r["status"]!="OBSERVED_AUTHORED_UNITY_REIMPORT":
        result["raw_error"]=r.get("error")
        require(not v["actual_Unity_import_verified"],"inconclusive_promoted")
        return result
    require(len(r["routes"])==len(m["routes"])==2 and len(r["textures"])==2,"actual_route_population")
    def same(a,b):
        return all(a[k]==b[k] for k in ("path","guid","file_id","sha256"))
    route_count=0
    for a,b in zip(m["routes"],r["routes"],strict=True):
        require(a["key"]==b["key"] and same(a["mesh"],b["mesh"]) and
            all(a[k]==b[k] for k in ("vertex_count","index_counts","base_vertices")),"actual_mesh_route")
        require(len(a["uv"])==len(b["uv"])==8 and all(abs(x-y)<1e-6 for x,y in zip(a["uv"],b["uv"],strict=True)),"route_UV")
        for k in ("materials","textures","shaders"):
            if k not in a:continue
            require(len(a[k])==len(b[k])==2 and all(same(x,y) for x,y in zip(a[k],b[k],strict=True)),"actual_"+k+"_route")
        route_count+=2
    result["actual_route_matches"]=route_count
    for t,o in zip(m["textures"],r["textures"],strict=True):
        require(same(t,o["identity"]),"actual_texture_identity")
        w,h=o["width"],o["height"]
        require(0<w<=32 and 0<h<=32 and len(o["mips"])==o["mip_count"],"actual_mip_population")
        mips=[]
        for n,mp in enumerate(o["mips"]):
            mw,mh=max(1,w>>n),max(1,h>>n)
            require((mp["level"],mp["width"],mp["height"])==(n,mw,mh),"actual_mip_dimensions")
            packed,normal=mp["packed"],mp["normal"]
            require(len(packed)==len(normal)==mw*mh*4 and
                all(type(x) in (int,float) and math.isfinite(x) for x in packed+normal),"actual_readback_shape")
            errors=[];normals=[];modes=set()
            for i in range(0,len(packed),4):
                a,b,c,d=packed[i:i+4];u,vv,zz,mode=normal[i:i+4]
                require(mode in (0,1),"observed_shader_macro")
                x=2*a*d-1 if mode==0 else 2*a-1
                y=2*b-1
                z=math.sqrt(max(0,1-x*x-y*y)) if mode==0 else 2*c-1
                errors.append(max(abs(x-u),abs(y-vv),abs(z-zz)))
                normals.append((u,vv,zz));modes.add(mode)
            mips.append(dict(level=n,dimensions=[mw,mh],pixels=mw*mh,
                unique_signed_normal_vectors=len(set(normals)),macro_modes=sorted(modes),
                independent_maximum_unpack_error=max(errors)))
        result["observations"].append(dict(guid=t["guid"],actual_format=o["format"],
            actual_graphics_format=o["graphics_format"],actual_mip_count=o["mip_count"],
            source_mip_count=t["expected_source"]["mip_count"],cpu_status=o["readback_status"],mips=mips))
    return result

def main():
    p=argparse.ArgumentParser()
    p.add_argument("archive",type=Path)
    p.add_argument("--sha256",required=True)
    a=p.parse_args()
    print(json.dumps(inspect(a.archive,a.sha256),indent=2,sort_keys=True))
if __name__=="__main__":
    main()
