#!/usr/bin/env python3
"""Strict count-only authored Shader48 Property NAME/TYPE parity with exported ShaderLab.

Original Property text is reconstructed privately from immutable Shader48's
m_ParsedForm via t3_particle108_source_propstate.serialize_properties;
the export is from the exact SAME AssetRipper shader GUID/trace. No names,
descriptions, defaults, code, GUIDs, private paths or property values are
returned, printed or serialized. This does not prove GPU binding or pixel parity.
"""
from __future__ import annotations
from collections import Counter
import re
from scripts.b49_shaderlab_pass_contract import remove_comments,mask_quoted_strings,SHADER_OPEN

STATUS="T3_PARTICLE108_PRIVATE_AUTHORED_PROPERTY_NAMES_TYPES_COMPARED"
IDENT=r"[_A-Za-z][_A-Za-z0-9]{0,127}"
PROPERTY_OPEN=re.compile(r"\bProperties\s*\{")
PROPERTY_DECL=re.compile(
    r'^\s*(?:\[[^\]\r\n]{1,160}\]\s*)*'
    r'(?P<name>'+IDENT+r')\s*\(\s*"(?:\\.|[^"\\])*"\s*,\s*'
    r'(?P<type>Color|Vector|Float|Int|2D|3D|Cube|2DArray|3DArray|CubeArray|Range\([^()\r\n]{1,130}\))'
    r'\s*\)\s*=\s*(?P<value>[^\r\n]+)\s*$'
)
PROPERTY_ATTR=re.compile(r'^\s*(?:\[[^\]\r\n]{1,160}\]\s*)+$')
ALLOWED=frozenset(("Color","Vector","Float","Int","2D","3D","Cube","2DArray","3DArray","CubeArray","Range"))
MAX_SHADERLAB=8_000_000
MAX_PROPERTIES=128

def _category(typ):
    return "Range" if typ.startswith("Range(") else typ

def _properties_body(shader_source, *, original_fragment=False):
    if type(shader_source) is not str or not 0<len(shader_source.encode("utf-8"))<=MAX_SHADERLAB:
        raise ValueError("T3_PROPERTY_OVERSIZE_OR_INVALID")
    if original_fragment:
        # Original is generated by strict serialized-authored source parser,
        # not arbitrary game text; wrapper used ONLY for bounded grammar scan.
        if not re.match(r'^\s*Properties\s*\{',shader_source):
            raise ValueError("T3_PROPERTY_SOURCE_FRAGMENT")
        shader_source='Shader "T3/PrivateSource" {\n'+shader_source+'\n}'
    cleaned=remove_comments(shader_source)
    masked=mask_quoted_strings(shader_source)
    root_open={m.end()-1 for m in SHADER_OPEN.finditer(cleaned)}
    prop_open={m.end()-1 for m in PROPERTY_OPEN.finditer(masked)}
    stack=[]
    bodies=[]
    roots=0
    balanced=True
    for offset,c in enumerate(masked):
        if c=="{":
            parent=stack[-1][0] if stack else None
            if offset in root_open and parent is None:
                kind="shader";roots+=1
            elif offset in prop_open and parent=="shader":
                kind="properties"
            else:
                kind="other"
            stack.append((kind,offset+1))
        elif c=="}":
            if not stack:
                balanced=False
                break
            kind,start=stack.pop()
            if kind=="properties":
                bodies.append(cleaned[start:offset])
    if stack or not balanced or roots!=1 or len(bodies)!=1:
        raise ValueError("T3_PROPERTY_ROOT_OR_BLOCK_TOPOLOGY")
    return bodies[0]

def _parse_authoring(shader_source, *, original_fragment=False):
    body=_properties_body(shader_source,original_fragment=original_fragment)
    rows={}
    for raw in body.splitlines():
        line=raw.strip()
        if not line or PROPERTY_ATTR.fullmatch(line):
            continue
        m=PROPERTY_DECL.fullmatch(line)
        if m is None:
            raise ValueError("T3_PROPERTY_DECLARATION_UNSUPPORTED")
        name=m.group("name")
        typ=_category(m.group("type"))
        if typ not in ALLOWED or name in rows or len(rows)>=MAX_PROPERTIES:
            raise ValueError("T3_PROPERTY_DUPLICATE_OR_UNSUPPORTED")
        # Deliberately do not compare defaults or descriptions:
        # source vectors/ranges/textures need separate semantic validation.
        rows[name]=typ
    if not rows:
        raise ValueError("T3_PROPERTY_EMPTY")
    return rows

def compare(original_authored_fragment,exact_exported_shader):
    """Public safe aggregate only; compare source-private name/type dictionaries."""
    source=_parse_authoring(original_authored_fragment,original_fragment=True)
    exported=_parse_authoring(exact_exported_shader,original_fragment=False)
    source_names=set(source);exported_names=set(exported)
    common=source_names&exported_names
    wrong=sum(source[name]!=exported[name] for name in common)
    missing=len(source_names-exported_names)
    extra=len(exported_names-source_names)
    sc=Counter(source.values());ec=Counter(exported.values())
    matched=(missing==0 and extra==0 and wrong==0)
    return {
        "schema_version":1,"status":STATUS,
        "original_authored_property_names_types_exact":matched,
        "counts":{
            "source_authored_property_count":len(source),
            "exported_authored_property_count":len(exported),
            "source_authored_texture_property_count":sum(sc[k] for k in ("2D","3D","Cube","2DArray","3DArray","CubeArray")),
            "exported_texture_property_count":sum(ec[k] for k in ("2D","3D","Cube","2DArray","3DArray","CubeArray")),
            "original_authored_property_names_missing_in_export":missing,
            "exported_property_names_not_authored_in_source":extra,
            "matched_name_different_type":wrong,
            "original_names_and_types_matched":len(common)-wrong,
        },
        "original_property_names_types_descriptions_defaults_published":False,
        "original_property_default_or_material_value_equivalence_proven":False,
        "original_shader_program_resource_binding_or_Android_pixel_proven":False,
    }
